class SettingsController extends ChangeNotifier {
  // Singleton Yapısı
  static final SettingsController _instance = SettingsController._internal();
  factory SettingsController() => _instance;
  SettingsController._internal();

  // Varsayılan Ayarlar
  ThemeMode _themeMode = ThemeMode.light;
  AppLanguage _language = AppLanguage.tr;

  // ── Kullanıcı Kayıt Deposu (uygulama yaşam döngüsü boyunca korunur) ──
  // email (lowercase-trimmed) → password eşleşmesi
  final Map<String, String> _registeredUsers = {};

  /// Yeni kullanıcı kaydeder. Aynı e-posta zaten varsa üzerine yazar.
  void registerUser(String email, String password) {
    _registeredUsers[email.trim().toLowerCase()] = password;
  }

  /// Verilen e-posta + şifre çifti kayıtlıysa true döner.
  bool validateLogin(String email, String password) {
    final key = email.trim().toLowerCase();
    return _registeredUsers.containsKey(key) &&
        _registeredUsers[key] == password;
  }

  /// Sadece e-posta kayıtlı mı? (şifre hatası ile e-posta bulunamadı hatasını ayırmak için)
  bool isEmailRegistered(String email) {
    return _registeredUsers.containsKey(email.trim().toLowerCase());
  }

  ThemeMode get themeMode => _themeMode;
  AppLanguage get language => _language;
  bool get isDarkMode => _themeMode == ThemeMode.dark;

  // Tema Değiştir
  void toggleTheme() {
    _themeMode = (_themeMode == ThemeMode.light) ? ThemeMode.dark : ThemeMode.light;
    notifyListeners();
  }

  // Dil Değiştir
  void setLanguage(AppLanguage lang) {
    _language = lang;
    notifyListeners();
  }

